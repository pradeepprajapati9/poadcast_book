<?php

namespace App\Http\Controllers\Admin;

use App\Http\Controllers\Controller;
use App\Models\AccessCode;
use App\Models\Book;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Inertia\Inertia;
use Inertia\Response;

class AccessCodeController extends Controller
{
    public function index(Request $request): Response
    {
        $bookId = $request->query('book');

        $codes = AccessCode::query()
            ->with(['book:id,title,slug'])
            ->when($bookId, fn ($q) => $q->where('book_id', $bookId))
            ->latest()
            ->paginate(10)
            ->withQueryString()
            ->through(fn (AccessCode $c) => [
                'id' => $c->id,
                'code' => $c->code,
                'book' => $c->book?->title,
                'book_slug' => $c->book?->slug,
                'duration_months' => $c->duration_months,
                'batch' => $c->batch,
                // Still surfaced so a code a reader has paid for cannot be
                // deleted by accident, even though nothing can redeem today.
                'redeemed' => $c->isRedeemed(),
            ]);

        return Inertia::render('Admin/Codes/Index', [
            'codes' => $codes,
            'books' => Book::orderBy('title')->get(['id', 'title']),
            'filters' => ['book' => $bookId],
            'summary' => ['total' => AccessCode::count()],
        ]);
    }

    // Codes are not generated by hand — BookController creates a book's single
    // code when the book itself is created.

    /**
     * Deleting a code deletes its book.
     *
     * A book and its code are one unit, so removing the code removes the book,
     * its chapters and their uploaded PDFs. This is irreversible, hence the
     * guard on redeemed codes: someone has already paid for that access.
     */
    public function destroy(AccessCode $code): RedirectResponse
    {
        if ($code->isRedeemed()) {
            return back()->withErrors([
                'code' => 'This code has been redeemed by a reader, so its book cannot be deleted.',
            ]);
        }

        $book = $code->book;

        if (! $book) {
            $code->delete();

            return back()->with('success', 'Orphan code deleted.');
        }

        $title = $book->title;
        $book->deleteWithFiles();

        return back()->with('success', "\"{$title}\" and its code were deleted.");
    }
}
